-- Dobri / slabi sosedje iz virov (zamenja prejšnjo ročno vneseno tabelo, ki je imela protislovja,
-- brokoli brez pravil in več pravil brez vira).
--
-- Viri:
--  BUND          Bund für Umwelt und Naturschutz Deutschland: "Mischkultur: Gute und schlechte Nachbarn".
--  Pušenjak      M. Pušenjak (KGZS), Zelenjavni vrt — "Dobri sosedje vrtnin in razdalja setve ali sajenja".
--  LWG           Bayerische Gartenakademie, Merkblatt 2104 "Mischkulturen im Gemüsegarten" (2020).
--  Varis 1991    A.-L. Varis, Agricultural Science in Finland: Effect of intercropping carrots and onions
--                on damage caused by the carrot fly (7 let poljskih poskusov; podprto tudi z
--                Wierzbicka & Majkowska-Gadomska 2012, Acta Agrobotanica).
--  Plantura, Gartenjournal — vrtnarska priročnika (kumare–paradižnik, paradižnik–čebula).
--
-- Pravilo: par je "good", če ga vsaj en vir navaja kot dobrega in noben kot slabega; "bad" obratno.
-- Kjer si viri nasprotujejo, para ni (nevtralno): Grah–Paradižnik, Grah–Krompir (BUND slab, Pušenjak dober).
-- Čebula–Korenje: LWG zadržek, a poljski poskusi (Varis 1991) kažejo korist → good.
-- Kohlgewächse = Zelje, Cvetača, Brokoli, Brstični ohrovt; "andere Kohlarten" (med sabo slabi) vključuje kolerabo.
-- BUND v vrstici Rote Beete navaja krompir hkrati kot dobrega in slabega; vrstica Kartoffeln ga navaja kot slabega → bad.
-- LWG opozarja, da vpliva sosedov ni lahko dokazati in si poročila pogosto nasprotujejo — to so praktične smernice.
-- Ena vrstica na par; aplikacija preverja obe smeri.

